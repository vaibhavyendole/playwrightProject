// Type of Operators
/*
1. Arithmatic Operator : + - / * % **
2. Assignment Operatopr : = +=  -=  *=  /=
3. Comparision Operator : ==   ===  !==  !===   < >  <=   >=
4. Logical Operator : AND OR  &&  || 
5. Increament / Decreament : Prefix ++Count | postfix Count++
*/

// 1.   Arithmatic Operator : + - / * % **
let a = 15;
let b = 2;
console.log(a+b); // 17
console.log(a-b); // 13
console.log(a/b); // 7.5
console.log(a*b); // 30
console.log(a%b); // 1 
console.log(a**b);// 225

//2. Increament Operator ++  -- 
//  Pre- Increament 
let num1 = 15
console.log(++num1);     // 16 
console.log(num1);       // 16

// Post Increament
let num2 = 20
console.log(num2++);    // 20
console.log(num2);21    // 21




