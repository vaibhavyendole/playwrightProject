// 1. for loop
// for(start condition, end condition, increament/decreament){
// code to execute}

// Print numb from 10 to 20
for(let i = 10; i<=20; i++){
    console.log(i);
}

// print num 50 to 25 in reverse
for(let i = 50; i>=25; i--){
    console.log(i)
}

// print the square of numbers 
for(let i = 5; i<=25; i+=2){
    console.log(`Square the number ${i} is ${i**2}`)
}
