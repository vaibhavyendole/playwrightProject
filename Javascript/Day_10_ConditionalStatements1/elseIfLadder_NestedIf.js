// 2. if()..else
let age = 30;
if(age>=18){
    console.log(`Yes age ${age} is greater than equal to 18`)
}
else{
    console.log(`No age ${age} is not greater than equal to 18`)
}
// output : Yes age 30 is greater than equal to 18

